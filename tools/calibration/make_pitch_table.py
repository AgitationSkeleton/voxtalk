"""Measure each Half-Life VOX word's pitch contour and write src/vox_pitch.h.

For every word file: remove the 137 ms feedback echo (loop filter from loopfilt.py),
track F0 by harmonic spacing, keep frames in the main speech, and fit a quadratic
in semitones over normalised time (robust, outliers rejected). The first 130 ms of
each word is echo-free and weighted more heavily. Only measurements are stored.

make_pitch_table.py <Half-Life>/valve/sound/vox"""
import sys, os, glob
import numpy as np
from scipy.signal import butter, lfilter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze import load, f0_comb, SR

LOOP = [0.261, 0.078, 0.025, 0.023]  # regression estimate at lags 1510..1513 (scaled below)
SKIP = {'_comma', '_period', 'bizwarn', 'bloop', 'buzwarn', 'dadeda', 'deeoo', 'doop', 'woop', 'endgame',
        'vox_login', 'null'}
HOP = 64
NSEG = 8
bb, ba = butter(2, [200 / (SR / 2), 2500 / (SR / 2)], 'band')


def deecho(y):
    x = y.copy()
    h = np.array(LOOP) * 1.15
    for n in range(1510, len(x)):
        acc = 0.0
        for k, c in enumerate(h):
            if n - 1510 - k >= 0: acc += c * y[n - 1510 - k]
        x[n] = y[n] - acc
    return x


def contour(path):
    y = load(path)
    x = deecho(y)
    f = f0_comb(x, n=768, hop=HOP, fmin=35, fmax=200)
    e = np.sqrt(np.convolve(lfilter(bb, ba, x) ** 2, np.ones(220) / 220, 'same'))
    centers = np.arange(len(f)) * HOP + 384
    en = e[np.minimum(centers, len(e) - 1)]
    ok = (~np.isnan(f)) & (en > e.max() * 0.25)
    # reject frames that jump away from their neighbours (nasals, echo residue)
    ff = np.where(ok, f, np.nan)
    med = np.array([np.nanmedian(ff[max(0, i - 3):i + 4]) if np.any(~np.isnan(ff[max(0, i - 3):i + 4])) else np.nan
                    for i in range(len(ff))])
    ok &= np.abs(12 * np.log2(np.where(ok, f, 1) / np.where(np.isnan(med), 1, med))) < 2.0
    idx = np.where(ok)[0]
    if len(idx) < 6:
        return None
    t = centers[idx] / SR
    st = 12 * np.log2(f[idx] / 100.0)
    t0, t1 = t[0], t[-1]
    if t1 - t0 < 0.05:
        return None
    u = (t - t0) / (t1 - t0)
    # median pitch in each of NSEG equal parts of the voiced span (semitones re 100 Hz)
    v = []
    for q in range(NSEG):
        sel = (u >= q / NSEG) & (u <= (q + 1) / NSEG)
        if sel.sum() == 0:
            v.append(np.nan)
        else:
            v.append(np.median(st[sel]))
    v = np.array(v)
    if np.isnan(v).all():
        return None
    # fill empty quarters from neighbours
    for q in range(NSEG):
        if np.isnan(v[q]):
            nb = [v[k] for k in (q - 1, q + 1) if 0 <= k < NSEG and not np.isnan(v[k])]
            v[q] = np.mean(nb) if nb else np.nanmedian(v)
    # Late jumps far above the first half come from weak nasal/echo frames, not the
    # voice: limit the second half to 3 semitones above the first half's peak.
    h = NSEG // 2
    v[h:] = np.minimum(v[h:], max(v[:h]) + 3)
    return np.clip(v, -16, 9)

if __name__ == '__main__':
    d = sys.argv[1]
    rows = {}
    for p in sorted(glob.glob(os.path.join(d, '*.wav'))):
        w = os.path.basename(p)[:-4].lower()
        if w in SKIP: continue
        v = contour(p)
        if v is not None: rows[w] = v
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'src', 'vox_pitch.h')
    with open(out, 'w', newline='\n') as f:
        f.write("// Generated by tools/calibration/make_pitch_table.py from Half-Life's sound/vox word\n")
        f.write('// files: median pitch of each eighth of every word\'s voiced speech, in fifths of\n')
        f.write('// a semitone relative to 100 Hz (measurements only). Sorted by word.\n')
        f.write('#pragma once\n\nstruct VoxPitch { const char *word; signed char st[8]; };  // fifths of a semitone re 100 Hz\n\n')
        f.write('static const VoxPitch VOX_PITCH[] = {\n')
        for w in sorted(rows):
            q = [int(round(v * 5)) for v in rows[w]]  # 0.2 st resolution
            f.write('    {"' + w + '", {' + ', '.join(str(z) for z in q) + '}},\n')
        f.write('};\n')
    print(f'wrote {len(rows)} contours to {out}')
    for w in ['your', 'team', 'stolen', 'enemy', 'has', 'flag', 'the', 'returned', 'captured']:
        if w in rows:
            hz = 100 * 2 ** (rows[w] / 12)
            print(f'  {w:10s} ' + '  '.join(f'{h:5.1f}' for h in hz) + ' Hz')
