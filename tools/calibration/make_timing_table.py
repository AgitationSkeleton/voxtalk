"""Generate src/vox_timing.h: the length (in samples at 11025 Hz) of every word
file in Half-Life's sound/vox folder. voxtalk uses it to give each known word the
same length as in the game, so sentences keep the game's timing.
make_timing_table.py <Half-Life>/valve/sound/vox [more vox dirs...]"""
import sys, os, glob, wave

SKIP = {'_comma', '_period', 'bizwarn', 'bloop', 'buzwarn', 'dadeda', 'deeoo', 'doop', 'woop', 'endgame',
        'vox_login', 'null'}
lengths = {}
for d in sys.argv[1:]:
    for p in glob.glob(os.path.join(d, '*.wav')):
        w = os.path.basename(p)[:-4].lower()
        if w in SKIP:
            continue
        with wave.open(p, 'rb') as f:
            n = f.getnframes() * 11025 // f.getframerate()
        lengths[w] = n
out = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'src', 'vox_timing.h')
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/calibration/make_timing_table.py from Half-Life\'s sound/vox\n')
    f.write('// word files: length of each word in samples at 11025 Hz (sorted by word).\n')
    f.write('#pragma once\n\nstruct VoxTiming { const char *word; unsigned short samples; };\n\n')
    f.write('static const VoxTiming VOX_TIMING[] = {\n')
    for w in sorted(lengths):
        f.write(f'    {{"{w}", {lengths[w]}}},\n')
    f.write('};\n')
print(f'wrote {len(lengths)} entries to {out}')
