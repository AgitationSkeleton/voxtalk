"""Generate shims_gen.c: the table mapping every imported Win32 function to its
shim, with argument-popping stubs for functions the engine imports but never
needs. Verifies each implemented shim's stdcall argument size against the real
Windows API (from MinGW's import libraries, collected in argbytes.txt).

gen_shims.py argbytes.txt out.c obj1.o [obj2.o ...]"""
import sys, re, subprocess

argfile, out, objs = sys.argv[1], sys.argv[2], sys.argv[3:]
KNOWN = {'InterlockedIncrement': 4, 'InterlockedDecrement': 4, 'InterlockedExchange': 8}
CDECL = {'wsprintfA'}

imports = []
for line in open(argfile):
    parts = line.split()
    if len(parts) < 2: continue
    dll, name = parts[0], parts[1]
    n = int(parts[2]) if len(parts) > 2 else KNOWN.get(name)
    if n is None and name not in CDECL:
        sys.exit(f'no argument size for {name}')
    imports.append((dll, name, n))

impl = {}  # name -> (symbol, bytes or None for cdecl)
for o in objs:
    for line in subprocess.run(['nm', o], capture_output=True, text=True, check=True).stdout.splitlines():
        m = re.match(r'^[0-9a-f]+ T (_shim_(\w+?)(?:@(\d+))?)$', line)
        if m:
            impl[m.group(2)] = (m.group(1), int(m.group(3)) if m.group(3) else None)

errors = []
for dll, name, n in imports:
    if name in impl:
        sym, b = impl[name]
        if name in CDECL:
            if b is not None: errors.append(f'{name} must be cdecl')
        elif b != n:
            errors.append(f'{name}: shim pops {b} bytes, API has {n}')
if errors:
    sys.exit('argument size mismatch:\n  ' + '\n  '.join(errors))

lines = ['// Generated by gen_shims.py - do not edit.', '#include "kernel.h"', '']
stubs_asm = []
entries = []
seen = set()
for dll, name, n in imports:
    if name in seen: continue
    seen.add(name)
    if name in impl:
        sym = impl[name][0]
        lines.append(f'extern char {name}__impl[] __asm__("{sym}");')
        entries.append(f'    {{"{dll}", "{name}", {name}__impl}},')
    else:
        lines.append(f'extern char {name}__stub[] __asm__("_stub_{name}");')
        lines.append(f'const char {name}__nm[] __attribute__((used)) = "{dll}!{name}";')
        stubs_asm.append(f'"_stub_{name}:\\n pushl $_{name}__nm\\n call _stub_hit\\n addl $4, %esp\\n xorl %eax, %eax\\n ret ${n}\\n"')
        entries.append(f'    {{"{dll}", "{name}", {name}__stub}},')

lines.append('')
lines.append('void stub_hit(const char *name) { kprintf("stub called: %s\\n", name); }')
lines.append('__asm__(".text\\n"')
lines += stubs_asm
lines.append(');')
lines.append('')
lines.append('const ShimEntry g_shims[] = {')
lines += entries
lines.append('    {0, 0, 0}};')
lines.append('''
void *shim_lookup(const char *dll, const char *name) {
    for (const ShimEntry *e = g_shims; e->name; e++)
        if (!strcmp(e->name, name)) return e->fn;
    return 0;
}''')
open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
print(f'{len(seen)} imports: {sum(1 for x in seen if x in impl)} implemented, {sum(1 for x in seen if x not in impl)} stubs')
